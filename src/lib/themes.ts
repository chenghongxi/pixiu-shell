import type { ITheme } from "@xterm/xterm";

export const GRAPHITE_BACKGROUND = "#1b1b1b";

// 弹层不透明度始终高于页面表面（页面 60% 时弹层约 86%），
// 避免亮色壁纸透过弹窗，同时跟随透明度设置自适应。
export function applyWindowOpacity(root: HTMLElement, value: number): void {
  root.style.setProperty("--window-opacity", `${value}%`);
  root.style.setProperty(
    "--popup-opacity",
    `${Math.round(100 - (100 - value) * 0.15)}%`,
  );
}

interface Palette {
  name: string;
  description: string;
  theme: ITheme;
}
function palette(
  background: string,
  foreground: string,
  cursor: string,
  colors: string[],
): ITheme {
  const [
    black,
    red,
    green,
    yellow,
    blue,
    magenta,
    cyan,
    white,
    brightBlack,
    brightRed,
    brightGreen,
    brightYellow,
    brightBlue,
    brightMagenta,
    brightCyan,
    brightWhite,
  ] = colors;
  return {
    background,
    foreground,
    cursor,
    cursorAccent: background,
    overviewRulerBorder: background,
    scrollbarSliderBackground: `${foreground}33`,
    scrollbarSliderHoverBackground: `${foreground}55`,
    scrollbarSliderActiveBackground: `${foreground}77`,
    selectionBackground: `${cursor}35`,
    black,
    red,
    green,
    yellow,
    blue,
    magenta,
    cyan,
    white,
    brightBlack,
    brightRed,
    brightGreen,
    brightYellow,
    brightBlue,
    brightMagenta,
    brightCyan,
    brightWhite,
  };
}
